"""Original raw-event revision semantics and exact author/direct clock aggregation."""
import os
for _k in ('OMP_NUM_THREADS','MKL_NUM_THREADS','OPENBLAS_NUM_THREADS','NUMEXPR_NUM_THREADS'):
    os.environ[_k]='1'
import argparse, time
from pathlib import Path
import common as c
import frozen_events as e

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--raw-root', required=True, type=Path)
    ap.add_argument('--author-root', required=True, type=Path,
                    help='Directory containing gt/ and unsynced/ author parquet folders')
    ap.add_argument('--direct-shot-mapping', required=True, type=Path)
    ap.add_argument('--author-shots', required=True, type=Path)
    ap.add_argument('--explicit-clock-case', required=True, type=Path)
    ap.add_argument('--output', required=True, type=Path)
    a=ap.parse_args(); started=time.monotonic(); contract=c.read(c.HERE/'input_contract.json')
    # Verify actual source bytes and proof content before creating any output.
    pins={'raw_event_metadata_files':[c.resolve(a.raw_root,r) for r in contract['raw_event_metadata']],
          'author_parquet_files':[c.resolve(a.author_root,r) for r in contract['author_parquet']]}
    prior=c.checked_csv(a.direct_shot_mapping,contract['direct_shot_mapping'])
    saved=c.checked_csv(a.author_shots,contract['author_shots'])
    conflict=c.read(a.explicit_clock_case); cp=contract['explicit_case']
    if c.canonical({k:conflict[k] for k in cp['fields']}) != cp['selected_fields_sha256']:
        raise ValueError('Explicit fixed clock evidence differs; no offset search is permitted')
    out=c.output_dir(a.output,[a.raw_root,a.author_root]); c.identity('EVENT_CLOCK_AGGREGATION',out)
    tables,residual=e.assemble(pins,prior,saved,conflict)
    checks={}
    for name, data in tables.items():
        e.csvout(out/name,data)
        c.checked_csv(out/name,contract['aggregate_outputs'][name])
        checks[name]=dict(rows=len(data),exact_ordered_fields=True,**c.pin(out/name))
    clocks=tables['event_clocks.csv']
    receipt=dict(status='PASS_EXACT_EVENT_CLOCK_RECONSTRUCTION',seconds=time.monotonic()-started,
        proof_inputs=[c.pin(p) for p in (a.direct_shot_mapping,a.author_shots,a.explicit_clock_case)],
        raw_inputs=[{k:r[k] for k in ('relative_path','sha256','bytes')} for rr in pins.values() for r in rr],
        outputs=checks,explicit_same_frame_signed_residual_s=residual,
        direct_accepted=sum(r['scenario']=='DIRECT_LITERAL' and r['clock_accepted'] for r in clocks),
        author_scenario_accepted=sum(r['scenario']=='AUTHOR3_PLUS_DIRECT_OTHER4' and r['clock_accepted'] for r in clocks),
        physical_synchronization_validated=False,new_independent_matches=0,new_training=False,
        limit='Proof files must themselves be regenerated by development_clock_sources to claim raw-source closure.')
    c.put(out/'completion.json',receipt)
    print(receipt['status'], {n:r['rows'] for n,r in checks.items()},flush=True)

if __name__=='__main__': main()
